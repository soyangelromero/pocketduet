/*
 * Generates a minimal, valid Nintendo DS firmware image (128 KB) for the melonDS core.
 *
 * It is NOT a copy of Nintendo's firmware: it contains no executable code, only the settings a game
 * needs to see (header, Wi-Fi calibration, one access point, user settings). The layout and default
 * values follow melonDS' own default-firmware generator (src/SPI_Firmware.cpp, GPL-3.0),
 * which is why the output is safe to ship and to regenerate at runtime.
 */
(function (root) {
  const LEN = 0x20000;
  const BBINIT = [
    0x03, 0x17, 0x40, 0x00, 0x1B, 0x6C, 0x48, 0x80, 0x38, 0x00, 0x35, 0x07, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0xB0, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xC7, 0xBB, 0x01, 0x24, 0x7F,
    0x5A, 0x01, 0x3F, 0x01, 0x3F, 0x36, 0x1D, 0x00, 0x78, 0x35, 0x55, 0x12, 0x34, 0x1C, 0x00, 0x01,
    0x0E, 0x38, 0x03, 0x70, 0xC5, 0x2A, 0x0A, 0x08, 0x04, 0x01, 0x00, 0x00, 0x00, 0xFF, 0xFF, 0xFE,
    0xFE, 0xFE, 0xFE, 0xFC, 0xFC, 0xFA, 0xFA, 0xFA, 0xFA, 0xFA, 0xF8, 0xF8, 0xF6, 0x00, 0x12, 0x14,
    0x12, 0x41, 0x23, 0x03, 0x04, 0x70, 0x35, 0x0E, 0x2C, 0x2C, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x0E, 0x00, 0x00, 0x12, 0x28, 0x1C];
  const RFINIT = [
    0x31, 0x4C, 0x4F, 0x21, 0x00, 0x10, 0xB0, 0x08, 0xFA, 0x15, 0x26, 0xE6, 0xC1, 0x01, 0x0E, 0x50,
    0x05, 0x00, 0x6D, 0x12, 0x00, 0x00, 0x01, 0xFF, 0x0E, 0x00, 0x02, 0x00, 0x00, 0x00, 0x00, 0x06,
    0x06, 0x00, 0x00, 0x00, 0x18, 0x00, 0x02, 0x00, 0x00];
  const CHANDATA = [
    0x1E, 0x0C, 0x0C, 0x0C, 0x0C, 0x0C, 0x0C, 0x0E, 0x0E, 0x0E, 0x0E, 0x0E, 0x0E, 0x0E, 0x16,
    0x26, 0x1C, 0x1C, 0x1C, 0x1D, 0x1D, 0x1D, 0x1E, 0x1E, 0x1E, 0x1E, 0x1F, 0x1E, 0x1F, 0x18,
    0x01, 0x4B, 0x4B, 0x4B, 0x4B, 0x4C, 0x4C, 0x4C, 0x4C, 0x4C, 0x4C, 0x4C, 0x4D, 0x4D, 0x4D,
    0x02, 0x6C, 0x71, 0x76, 0x5B, 0x40, 0x45, 0x4A, 0x2F, 0x34, 0x39, 0x3E, 0x03, 0x08, 0x14];

  // CRC-16 used by the DS firmware (reflected polynomial 0xA001)
  function crc16(b, start, len, init) {
    let c = init;
    for (let i = start; i < start + len; i++) {
      c ^= b[i];
      for (let j = 0; j < 8; j++) c = (c & 1) ? (c >>> 1) ^ 0xA001 : c >>> 1;
    }
    return c & 0xFFFF;
  }
  const put16 = (b, o, v) => { b[o] = v & 0xFF; b[o + 1] = (v >> 8) & 0xFF; };

  function makeFirmware(opts) {
    opts = opts || {};
    const mac = opts.mac || [0x00, 0x09, 0xBF, 0x11, 0x22, 0x33];
    const name = (opts.name || "melonDS").slice(0, 10);
    const lang = opts.language == null ? 1 : opts.language; // 0 JP, 1 EN, 2 FR, 3 DE, 4 IT, 5 ES
    const fw = new Uint8Array(LEN).fill(0xFF);
    fw.fill(0, 0, 0x1D);

    // --- header (512 bytes) ---
    fw.fill(0, 0x1D, 0x200);
    fw[0x1D] = 0x20;                         // console type: DS Lite
    fw.set([0x4D, 0x45, 0x4C, 0x4E], 0x08);  // identifier "MELN"
    put16(fw, 0x20, (0x7FE00 & (LEN - 1)) >> 3); // user settings offset
    put16(fw, 0x2C, 0x138);                  // wifi config length
    fw[0x2F] = 6;                            // wifi version W006
    fw.set([0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0x00], 0x30);
    fw.set(mac, 0x36);
    put16(fw, 0x3C, 0x3FFE);                 // enabled channels
    fw[0x3E] = 0xFF; fw[0x3F] = 0xFF;
    fw[0x40] = 3; fw[0x41] = 0x94; fw[0x42] = 0x29; fw[0x43] = 0x02;
    [0x0002, 0x0017, 0x0026, 0x1818, 0x0048, 0x4840, 0x0058, 0x0042, 0x0146, 0x8064, 0xE6E6, 0x2443, 0x000E, 0x0001, 0x0001, 0x0402]
      .forEach((v, i) => put16(fw, 0x44 + i * 2, v));
    fw.set(BBINIT, 0x64);
    fw[0xCD] = 0;
    fw.set(RFINIT, 0xCE);
    fw[0xF7] = 0x02;
    fw.set(CHANDATA, 0xF8);
    fw.fill(0xFF, 0x134, 0x134 + 46);
    put16(fw, 0x2A, crc16(fw, 0x2C, 0x138, 0x0000)); // wifi config checksum
    fw[0x2FF] = 0x80;

    // --- user settings (two copies) ---
    const user = (0x7FE00 & (LEN - 1));
    for (let k = 0; k < 2; k++) {
      const o = user + k * 0x100;
      fw.fill(0, o, o + 0x100);
      put16(fw, o + 0x00, 5);                // version
      fw[o + 0x03] = 1; fw[o + 0x04] = 1;    // birthday 1/1
      for (let i = 0; i < name.length; i++) put16(fw, o + 0x06 + i * 2, name.charCodeAt(i));
      put16(fw, o + 0x1A, name.length);
      put16(fw, o + 0x64, lang | 0x30);      // language | backlight max
      put16(fw, o + 0x72, crc16(fw, o, 0x70, 0xFFFF));
    }

    // --- Wi-Fi access points (3 x 256 bytes, 0x400 before the user settings) ---
    const ap = user - 0x400;
    for (let k = 0; k < 3; k++) {
      const o = ap + k * 0x100;
      fw.fill(0, o, o + 0x100);
      if (k === 0) { for (let i = 0; i < 7; i++) fw[o + 0x40 + i] = "melonAP".charCodeAt(i); fw[o + 0xE7] = 0x00; }
      else fw[o + 0xE7] = 0xFF;              // not configured
      fw[o + 0xEF] = 0x01;                   // connection configured
      put16(fw, o + 0xFE, crc16(fw, o, 0xFE, 0x0000));
    }
    return fw;
  }

  root.makeFirmware = makeFirmware;
  root.dsFirmwareCrc16 = crc16;
})(typeof window !== "undefined" ? window : globalThis);
